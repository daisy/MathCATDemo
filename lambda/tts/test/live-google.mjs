// Sends real MathCAT SSML to Google in every supported language. Checks that each
// request returns audio and a time for every mark, and saves the audio for listening.
// This makes billable requests.
//
//   GOOGLE_TTS_API_KEY=... node test/live-google.mjs [--lang en,zh-cn] [--out DIR]

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { HttpError } from '../lib/errors.js';
import { isTooLong, prepareGoogleSsml } from '../lib/google-ssml.js';
import { wrapSpeak } from '../lib/ssml.js';
import { localeFromVoice, voiceForLang } from '../lib/voices.js';
import { synthesize } from '../providers/google.js';

const { values: args } = parseArgs({
  options: {
    lang: { type: 'string' },
    out: { type: 'string', default: path.join(os.tmpdir(), 'mathcat-tts-live') },
  },
});

if (!process.env.GOOGLE_TTS_API_KEY) {
  console.error('Set GOOGLE_TTS_API_KEY first.');
  process.exit(2);
}

// Generated by MathCAT (ClearSpeak, Verbose, bookmarks on).
const samples = JSON.parse(
  fs.readFileSync(new URL('./ssml-samples.json', import.meta.url), 'utf8')
);

// Languages with a voice but no MathCAT rules yet.
for (const lang of ['da', 'is', 'it', 'nl']) {
  samples.push({ lang, name: 'voice only', ssml: "<mark name='a'/> x <mark name='b'/> 2" });
}

// Returns a list of problems (empty if the marks are fine).
function checkMarks(marks, expected) {
  const problems = [];
  const got = marks.map((mark) => mark.value);
  const missing = expected.filter((name) => !got.includes(name));
  if (missing.length) {
    problems.push(`${missing.length} of ${expected.length} marks missing: ${missing.join(' ')}`);
  } else if (got.join() !== expected.join()) {
    problems.push('marks are duplicated or out of order');
  }
  if (marks.some((mark) => !Number.isFinite(mark.time) || mark.time < 0)) {
    problems.push('a mark has an invalid time');
  }
  if (marks.length > 1 && marks[0].time === marks.at(-1).time) {
    problems.push('all marks have the same time');
  }
  return problems;
}

// MP3 data starts with an ID3 tag or an MPEG frame sync.
function isMp3(audio) {
  return audio.toString('latin1', 0, 3) === 'ID3' || (audio[0] === 0xff && (audio[1] & 0xe0) === 0xe0);
}

// Waits and retries when Google's per-minute quota is used up.
async function synthesizeWithRetry(request) {
  for (let attempt = 1; ; attempt++) {
    try {
      return await synthesize(request);
    } catch (err) {
      if (attempt === 4 || !err.message.startsWith('Google TTS error 429')) {
        throw err;
      }
      console.log('(per-minute quota reached; waiting 30 seconds)');
      await new Promise((resolve) => setTimeout(resolve, 30000));
    }
  }
}

async function runSample({ lang, name, ssml: text }) {
  const voice = voiceForLang('google', lang);
  const ssml = wrapSpeak(text, voice, 'google');
  const prepared = prepareGoogleSsml(ssml, localeFromVoice(voice));
  const info = `${voice}, ${Buffer.byteLength(prepared.ssml)} bytes, ${prepared.names.length} marks`;

  let result;
  try {
    result = await synthesizeWithRetry({ ssml, voice });
  } catch (err) {
    if (err instanceof HttpError && err.statusCode === 413 && isTooLong(prepared.ssml)) {
      return { status: 'TOO LONG', info, problems: [] };
    }
    return { status: 'FAIL', info, problems: [err.message] };
  }

  const audio = Buffer.from(result.audioBase64, 'base64');
  const file = path.join(args.out, `${lang}-${name.replaceAll(' ', '-')}.mp3`);
  fs.writeFileSync(file, audio);

  const problems = checkMarks(result.marks, prepared.names);
  if (!isMp3(audio)) {
    problems.push('audio is not MP3');
  }
  return { status: problems.length ? 'FAIL' : 'ok', info, problems };
}

const wanted = args.lang?.toLowerCase().split(',');
const selected = samples.filter((sample) => !wanted || wanted.includes(sample.lang));
if (!selected.length) {
  console.error(`No samples for --lang ${args.lang}`);
  process.exit(2);
}

fs.mkdirSync(args.out, { recursive: true });
const counts = { ok: 0, 'TOO LONG': 0, FAIL: 0 };
for (const sample of selected) {
  const { status, info, problems } = await runSample(sample);
  counts[status]++;
  console.log(`${status.padEnd(8)} ${sample.lang.padEnd(5)} ${sample.name} (${info})`);
  for (const problem of problems) {
    console.log(`           ${problem}`);
  }
}

console.log(`\n${counts.ok} ok, ${counts['TOO LONG']} too long for Google, ${counts.FAIL} failed`);
console.log(`Audio saved in ${args.out}`);
process.exitCode = counts.FAIL ? 1 : 0;
